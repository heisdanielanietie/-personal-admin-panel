import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
const testRequire=createRequire(import.meta.url);
const jsdomPath=process.env.STUDIO_TEST_JSDOM;
const {JSDOM}=await import(jsdomPath?pathToFileURL(testRequire.resolve(jsdomPath)).href:'jsdom');
const m={exports:{}};
new Function('exports',ts.transpileModule(fs.readFileSync('lib/editor.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText)(m.exports);
const dom=new JSDOM('');
global.DOMParser=dom.window.DOMParser;
global.XMLSerializer=dom.window.XMLSerializer;
global.btoa=value=>Buffer.from(value,'binary').toString('base64');
const {sanitizeSvgImage,safeUrl}=m.exports;
const source='<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" onload="alert(1)"><defs><linearGradient id="brand"><stop offset="0" stop-color="#7c3aed"/></linearGradient></defs><rect width="100" height="100" fill="url(#brand)"/><script>alert(1)</script><foreignObject><iframe src="https://example.com"></iframe></foreignObject><image href="https://example.com/remote.png"/><path fill="url(https://example.com/x)" d="M0 0L10 10"/></svg>';
const value=sanitizeSvgImage(source);
assert(safeUrl(value,true));
const clean=Buffer.from(value.split(',')[1],'base64').toString('utf8');
const result=new dom.window.DOMParser().parseFromString(clean,'image/svg+xml'),root=result.documentElement;
assert.equal(root.localName,'svg');
assert.equal(root.hasAttribute('onload'),false);
assert.equal(root.querySelector('script'),null);
assert.equal(root.querySelector('foreignObject'),null);
assert.equal(root.querySelector('iframe'),null);
assert.equal(root.querySelector('image'),null);
assert.equal(root.querySelector('path').hasAttribute('fill'),false);
assert.equal(root.querySelector('rect').getAttribute('fill'),'url(#brand)');
assert.throws(()=>sanitizeSvgImage('<!DOCTYPE svg [<!ENTITY x SYSTEM "https://example.com">]><svg xmlns="http://www.w3.org/2000/svg">&x;</svg>'),/unsupported XML declarations/);
assert.throws(()=>sanitizeSvgImage('<html><body>Not an SVG</body></html>'),/not a valid SVG/);
assert.throws(()=>sanitizeSvgImage('x'.repeat(750_001)),/smaller than 750 KB/);
dom.window.close();
console.log('PASS: SVG validation, dangerous element/attribute removal, local paint references, size limits and data-image URL acceptance.');
